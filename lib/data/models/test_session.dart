class TestSession {
  const TestSession({
    required this.id,
    required this.passageId,
    required this.passageTitleSnapshot,
    required this.mode,
    required this.configuredDuration,
    required this.actualElapsedDuration,
    required this.characterToWordRatio,
    required this.startedAt,
    this.completedAt,
    this.totalCharactersTyped = 0,
    this.totalWordsTyped = 0,
    this.grossWpm = 0,
    this.netWpm = 0,
    this.accuracy = 0,
    this.totalErrors = 0,
    this.omissions = 0,
    this.substitutions = 0,
    this.insertions = 0,
    this.backspaceCount = 0,
    this.completedRepetitions = 0,
    this.isCompleted = false,
  });
  final String id, passageId, passageTitleSnapshot, mode;
  final int configuredDuration,
      actualElapsedDuration,
      characterToWordRatio,
      totalCharactersTyped,
      totalWordsTyped,
      totalErrors,
      omissions,
      substitutions,
      insertions,
      backspaceCount,
      completedRepetitions;
  final double grossWpm, netWpm, accuracy;
  final DateTime startedAt;
  final DateTime? completedAt;
  final bool isCompleted;
  factory TestSession.fromMap(Map<String, Object?> m) => TestSession(
    id: m['id'] as String,
    passageId: m['passage_id'] as String,
    passageTitleSnapshot: m['passage_title_snapshot'] as String,
    mode: m['mode'] as String,
    configuredDuration: m['configured_duration'] as int,
    actualElapsedDuration: m['actual_elapsed_duration'] as int,
    characterToWordRatio: m['character_to_word_ratio'] as int,
    startedAt: DateTime.parse(m['started_at'] as String),
    completedAt: m['completed_at'] == null
        ? null
        : DateTime.parse(m['completed_at'] as String),
    totalCharactersTyped: m['total_characters_typed'] as int,
    totalWordsTyped: m['total_words_typed'] as int,
    grossWpm: (m['gross_wpm'] as num).toDouble(),
    netWpm: (m['net_wpm'] as num).toDouble(),
    accuracy: (m['accuracy'] as num).toDouble(),
    totalErrors: m['total_errors'] as int,
    omissions: m['omissions'] as int,
    substitutions: m['substitutions'] as int,
    insertions: m['insertions'] as int,
    backspaceCount: m['backspace_count'] as int,
    completedRepetitions: m['completed_repetitions'] as int,
    isCompleted: (m['is_completed'] as int) == 1,
  );
  Map<String, Object?> toMap() => {
    'id': id,
    'passage_id': passageId,
    'passage_title_snapshot': passageTitleSnapshot,
    'mode': mode,
    'configured_duration': configuredDuration,
    'actual_elapsed_duration': actualElapsedDuration,
    'character_to_word_ratio': characterToWordRatio,
    'started_at': startedAt.toIso8601String(),
    'completed_at': completedAt?.toIso8601String(),
    'total_characters_typed': totalCharactersTyped,
    'total_words_typed': totalWordsTyped,
    'gross_wpm': grossWpm,
    'net_wpm': netWpm,
    'accuracy': accuracy,
    'total_errors': totalErrors,
    'omissions': omissions,
    'substitutions': substitutions,
    'insertions': insertions,
    'backspace_count': backspaceCount,
    'completed_repetitions': completedRepetitions,
    'is_completed': isCompleted ? 1 : 0,
  };
}
